#!/usr/bin/env bash
# lkml-author-finalize-bundle.sh — Generate the standalone finalize file.
#
# Usage: lkml-author-finalize-bundle.sh --output FILE
#        lkml-author-finalize-bundle.sh --check FILE
#        lkml-author-finalize-bundle.sh -h|--help
#
# The runner executes one POSIX sh file without this checkout installed.
# Embed the finalize script and its transitive script dependencies into a
# deterministic wrapper. --output replaces FILE atomically, mode 0755;
# its directory must exist. --check writes nothing and exits 0 only for
# a regular, non-symlink executable file with exactly the current bytes.

set -euo pipefail

script_dir="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"
usage() { sed -n '2,/^set -euo/{ /^#/s/^# \?//p }' "$0"; }

if [[ $# == 1 && ( "$1" == -h || "$1" == --help ) ]]; then usage; exit 0; fi
if [[ $# != 2 || ( "$1" != --output && "$1" != --check ) || -z "$2" ]]; then
    echo 'Error: usage: lkml-author-finalize-bundle.sh --output FILE | --check FILE.' >&2
    exit 1
fi
mode="$1"; dest="$2"
files=(lkml-author-finalize.sh lkml-series-check.sh lkml-series-check-py.py)
for file in "${files[@]}"; do
    [[ -f "$script_dir/$file" ]] || { echo "Error: missing source $script_dir/$file." >&2; exit 1; }
done

render() {
    cat <<'SH'
#!/bin/sh
# Generated by lkml-author-finalize-bundle.sh from:
# lkml-author-finalize.sh, lkml-series-check.sh,
# lkml-series-check-py.py. Do not edit this file.

for program in bash python3 git grep; do
    if ! command -v "$program" >/dev/null 2>&1; then
        printf 'lkml-author-finalize-bundle: %s is missing from PATH.\n' "$program" >&2
        exit 1
    fi
done

bundle_tmp=$(mktemp -d "${TMPDIR:-/tmp}/lkml-author-finalize.XXXXXXXX") || exit 1
child=''
# shellcheck disable=SC2329  # called by the EXIT trap
cleanup() {
    if [ -n "$child" ]; then
        # Bash and its foreground Git command share a private process group.
        # Signal both so Bash can run its reply-restoring trap promptly;
        # until that group exists, signal the child alone.
        # kill -s, not -TERM: dash does not take `--` after `-TERM`.
        kill -s TERM -- "-$child" 2>/dev/null || kill -s TERM "$child" 2>/dev/null || :
        # The group is outside the caller's own, so a KILL sent to this
        # file never reaches it: a handler that hangs is killed from here.
        ( sleep 5; kill -s KILL -- "-$child" ) </dev/null >/dev/null 2>&1 &
        watchdog=$!
        wait "$child" 2>/dev/null || :
        kill "$watchdog" 2>/dev/null || :
    fi
    rm -rf -- "$bundle_tmp"
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
SH
    for file in "${files[@]}"; do
        printf "base64 -d > \"\$bundle_tmp/%s\" <<'LKML_BUNDLE_%s' || exit 1\n" "$file" "${file//[^a-zA-Z0-9]/_}"
        base64 < "$script_dir/$file" | fold -w 76
        printf 'LKML_BUNDLE_%s\n' "${file//[^a-zA-Z0-9]/_}"
    done
    cat <<'SH'
chmod 0755 "$bundle_tmp/lkml-author-finalize.sh" "$bundle_tmp/lkml-series-check.sh"
# exec keeps the new session leader's PID as the process-group ID.
python3 -c 'import os, sys; os.setsid(); os.execvp("bash", ["bash", sys.argv[1]])' \
    "$bundle_tmp/lkml-author-finalize.sh" &
child=$!
wait "$child"
rc=$?
child=''
exit "$rc"
SH
}

if [[ "$mode" == --check ]]; then
    if [[ -L "$dest" ]]; then
        echo "check: STALE    $dest (is a symlink)"; exit 1
    elif [[ ! -e "$dest" ]]; then
        echo "check: MISSING  $dest"; exit 1
    elif [[ ! -f "$dest" ]]; then
        echo "check: STALE    $dest (not a regular file)"; exit 1
    elif [[ ! -x "$dest" ]]; then
        echo "check: STALE    $dest (not executable)"; exit 1
    elif ! cmp -s -- "$dest" <(render); then
        echo "check: STALE    $dest (differs from current sources)"; exit 1
    fi
    echo "check: ok       $dest"
else
    dir="$(dirname -- "$dest")"
    [[ -d "$dir" ]] || { echo "Error: output directory '$dir' does not exist." >&2; exit 1; }
    [[ ! -d "$dest" ]] || { echo "Error: output '$dest' is a directory." >&2; exit 1; }
    tmp="$(mktemp "$dir/.lkml-author-finalize-bundle.XXXXXXXX")"
    trap 'rm -f -- "$tmp"' EXIT
    render > "$tmp"
    chmod 0755 "$tmp"
    mv -fT -- "$tmp" "$dest"
    trap - EXIT
    echo "output: wrote $dest"
fi
